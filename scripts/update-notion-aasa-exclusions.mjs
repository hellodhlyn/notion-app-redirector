import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const NOTION_APP_ID = "LBQJ96FQ8D.notion.id";
const SOURCES = [
  "https://www.notion.so/apple-app-site-association",
  "https://app.notion.com/.well-known/apple-app-site-association",
];
const snapshotPath = fileURLToPath(
  new URL("../src/notion-aasa-exclusions.js", import.meta.url),
);

async function loadExcludedPaths(source) {
  const response = await fetch(source, {
    headers: {
      accept: "application/json, application/octet-stream",
      "user-agent": "Mozilla/5.0",
    },
  });
  if (!response.ok) {
    throw new Error(`${source} returned HTTP ${response.status}`);
  }

  const body = await response.json();
  const details = body.applinks?.details?.find((item) =>
    item.appIDs?.includes(NOTION_APP_ID),
  );
  if (!details?.components) {
    throw new Error(`${source} does not contain ${NOTION_APP_ID} components`);
  }

  const paths = details.components
    .filter((component) => component.exclude === true)
    .map((component) => component["/"]);
  if (paths.some((path) => typeof path !== "string")) {
    throw new Error(`${source} contains an unsupported exclusion component`);
  }
  return paths;
}

function renderSnapshot(paths) {
  return [
    "// Generated by scripts/update-notion-aasa-exclusions.mjs.",
    "// Source: Notion apple-app-site-association for LBQJ96FQ8D.notion.id.",
    `var notionAasaExcludedPathPatterns = Object.freeze(${JSON.stringify(paths, null, 2)});`,
    "",
  ].join("\n");
}

const snapshots = await Promise.all(SOURCES.map(loadExcludedPaths));
const reference = JSON.stringify(snapshots[0]);
if (snapshots.some((snapshot) => JSON.stringify(snapshot) !== reference)) {
  throw new Error("Notion hosts expose different AASA exclusion rules");
}

const expected = renderSnapshot(snapshots[0]);
if (process.argv.includes("--check")) {
  const actual = await readFile(snapshotPath, "utf8");
  if (actual !== expected) {
    throw new Error(
      "Notion AASA exclusions changed; run this script without --check and review the diff",
    );
  }
} else {
  await writeFile(snapshotPath, expected);
}
